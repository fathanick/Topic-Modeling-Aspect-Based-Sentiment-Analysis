"""Provenance audit for every figure embedded in the manuscript.

For each figure: which script produced it, which artifact it reads, how many
rows that artifact has, and the file hashes. Fails if a PNG in
output/figures/ has no recorded producer or if an embedded image does not
hash-match the file on disk.

Run: ../.venv/bin/python scripts/audit_figure_provenance.py
"""
import hashlib
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "output" / "figures"
DOCX = ROOT.parent / "Manuscript" / "Manuscript-v3-revised.docx"

PRODUCERS = {
    # manuscript Fig: (png, script, source artifact)
    1: ("fig1_workflow.png", "scripts/make_paper_figures.py", "conceptual — from model_manifest.json"),
    2: ("fig_bertopic_pipeline.png", "scripts/make_method_figures.py", "output/topic_modeling_final/model_manifest.json"),
    3: ("fig_prompt.png", "scripts/make_method_figures.py", "src/sentiment_analysis/sentence_absa.py SYSTEM_PROMPT"),
    4: ("fig2_topic_sizes.png", "scripts/make_paper_figures.py", "output/topic_modeling_final/topics_summary.csv"),
    5: ("fig3_topic_words.png", "scripts/make_paper_figures.py", "output/topic_modeling_final/topics_summary.csv"),
    6: ("fig_topic_by_destination.png", "scripts/make_composite_figures.py", "output/sentence_absa/kalimat_aspek_sentimen.csv + topic_x_destination_pct.csv"),
    7: ("fig_aspects_combined.png", "scripts/make_composite_figures.py", "output/sentence_absa/kalimat_aspek_sentimen.csv"),
    8: ("fig7_aspect_destination.png", "scripts/make_fig6_aspect_by_destination.py", "output/sentence_absa/kalimat_aspek_sentimen.csv"),
}


def md5(b):
    return hashlib.md5(b).hexdigest()


def main():
    z = zipfile.ZipFile(DOCX)
    media = sorted(n for n in z.namelist() if n.startswith("word/media/"))
    assert len(media) == len(PRODUCERS), (len(media), len(PRODUCERS))
    rows = []
    ok = True
    for i, name in enumerate(media, 1):
        png, script, src = PRODUCERS[i]
        p = FIG / png
        disk = md5(p.read_bytes())
        embedded = md5(z.read(name))
        match = disk == embedded
        ok &= match
        png_bytes = p.read_bytes()
        software = b"Matplotlib" in png_bytes
        ok &= software
        rows.append({
            "fig": i, "file": png, "script": script, "source": src,
            "bytes": len(png_bytes), "md5": disk,
            "embedded_matches_disk": match, "matplotlib_signature": software,
        })
    print(json.dumps(rows, indent=1))
    print()
    print("all figures generated by Matplotlib and embedded verbatim:" , ok)
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
